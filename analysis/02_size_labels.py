"""02 Size labels: can SMB and SME be told apart? (HYGIENE_LOG H10)

Backtest 1: ARR per license (Renewal ARR / Sold Licenses on renewals; New Committed
ARR / Sold Licenses on New Opportunity) by Company Size label.
Backtest 2: accounts that carry more than one size label.
Writes outputs/02_size_label_ppl.csv and outputs/02_multi_label_accounts.csv.
"""
import pandas as pd

from common import OUT, RT_NEW, SIZE_ORDER, load, renewals

pd.set_option("display.width", 250)
pd.set_option("display.max_columns", 50)

SIZE = "Company Size (Employees)"
TINY_ARR = 1095.60  # 1-2 seats at the $547.80 list point; partner long tail


def profile(d: pd.DataFrame, arr: str) -> pd.DataFrame:
    g = d.groupby(SIZE)
    return pd.DataFrame({
        "rows": g.size(),
        "ppl_p25": g["ppl"].quantile(.25), "ppl_med": g["ppl"].median(), "ppl_p75": g["ppl"].quantile(.75),
        "lic_med": g["Sold Licenses"].median(), "lic_p75": g["Sold Licenses"].quantile(.75),
        "arr_med": g[arr].median(), "arr_p75": g[arr].quantile(.75),
    }).reindex(SIZE_ORDER).round(0)


df = load()

r = renewals(df)
r = r[r["Renewal ARR"] > 0].assign(ppl=lambda x: x["Renewal ARR"] / x["Sold Licenses"])
tiny = r["Renewal ARR"] <= TINY_ARR + 0.01
nb = df[(df["Opportunity Record Type"] == RT_NEW) & (df["New Committed ARR"] > 0)]
nb = nb.assign(ppl=lambda x: x["New Committed ARR"] / x["Sold Licenses"])

tables = {
    "renewal_all": profile(r, "Renewal ARR"),
    "renewal_excl_tiny": profile(r[~tiny], "Renewal ARR"),
    "new_opp": profile(nb, "New Committed ARR"),
}
for name, t in tables.items():
    print(f"\n== {name} (ppl = ARR per license) ==")
    print(t.to_string())
pd.concat(tables, names=["cut"]).to_csv(OUT / "02_size_label_ppl.csv")

print(f"\nRenewals with ARR <= ${TINY_ARR:,.2f}, by label:", r[tiny][SIZE].value_counts().reindex(SIZE_ORDER, fill_value=0).to_dict())
ts = r[tiny & r[SIZE].eq("SMB")]
print("  SMB tiny: Generated by", ts["Generated by"].value_counts().to_dict(),
      "| source", ts["Reporting Source"].value_counts().to_dict(), "| geo", ts["Geo"].value_counts().to_dict())

# Backtest 2: accounts carrying more than one label
d = df.dropna(subset=["Account Name", SIZE])
labels = d.groupby("Account Name")[SIZE].agg(lambda s: "/".join(sorted(s.unique())))
multi = labels[labels.str.contains("/")]
print(f"\nAccounts with >1 size label: {len(multi)} of {len(labels)} -> combos {multi.value_counts().to_dict()}")
mrows = d[d["Account Name"].isin(multi.index)]
consistent = mrows.groupby("Account Name")[["Geo", "Industry", "Region"]].nunique().le(1).all(axis=1)
print(f"  same Geo/Industry/Region across their rows: {int(consistent.sum())} of {len(multi)}")
sme_accts = set(d.loc[d[SIZE] == "SME", "Account Name"])
print(f"  SME accounts also labelled SMB elsewhere: {len(multi)} of {len(sme_accts)}")
(mrows.sort_values(["Account Name", "Close Date"])
      [["Account Name", SIZE, "Opportunity Record Type", "Deal Type", "Close Date", "Geo", "Industry", "Sold Licenses"]]
      .to_csv(OUT / "02_multi_label_accounts.csv", index=False))
